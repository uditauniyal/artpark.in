// Download the real photos and PDFs used on artpark.in project pages and every artpark.in-hosted
// document linked anywhere, so the new site does not depend on Squarespace.
// Writes src/data/projects-media.json (images, processed by tools/images.cjs) and public/docs/*.pdf.
const fs = require('fs');
const path = require('path');
const https = require('https');

const ROOT = path.resolve(__dirname, '..');
const CAP = path.join(ROOT, 'research', 'artpark-in');
const IMG = path.join(ROOT, 'research', 'img', 'projects');
const DOCS = path.join(ROOT, 'public', 'docs');
fs.mkdirSync(IMG, { recursive: true });
fs.mkdirSync(DOCS, { recursive: true });

const get = (url, dest) => new Promise((resolve) => {
  if (fs.existsSync(dest) && fs.statSync(dest).size > 0) return resolve(true);
  const req = https.get(url, { headers: { 'User-Agent': 'Mozilla/5.0' } }, (res) => {
    if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) { res.resume(); return get(new URL(res.headers.location, url).href, dest).then(resolve); }
    if (res.statusCode !== 200) { res.resume(); return resolve(false); }
    const f = fs.createWriteStream(dest); res.pipe(f); f.on('finish', () => f.close(() => resolve(true)));
  });
  req.on('error', () => resolve(false));
  req.setTimeout(60000, () => { req.destroy(); resolve(false); });
});

const SKIP = /chatgpt|logo|noun-|icon|favicon|ARTPARK\+with\+IISc|screenshot\+2026-05-1[23]|govtwhite/i;

(async () => {
  const projects = require(path.join(ROOT, 'src', 'data', 'projects.cjs'));
  const media = [];
  for (const p of projects) {
    const d = JSON.parse(fs.readFileSync(path.join(CAP, p.file + '.json'), 'utf8'));
    const seen = new Set();
    let n = 0;
    for (const im of d.images) {
      const src = im.src.split('?')[0].replace(/\/$/, '');
      if (seen.has(src) || SKIP.test(src) || im.w < 260) continue;
      seen.add(src);
      const ext = (path.extname(src) || '.jpg').toLowerCase().replace('.jpeg', '.jpg');
      const local = path.join(IMG, `${p.slug}-${n}${ext}`);
      if (await get(src + '?format=2500w', local)) {
        media.push({ out: `projects/${p.slug}-${n}.webp`, src: path.relative(ROOT, local).replace(/\\/g, '/'), maxW: 1600, subject: im.alt || '', source: d.url, sourceImage: src, project: p.slug, order: n });
        n++;
      }
    }
    process.stdout.write(`${p.slug}:${n} `);
  }
  fs.writeFileSync(path.join(ROOT, 'src', 'data', 'projects-media.json'), JSON.stringify({ _note: 'Photos from artpark.in project pages (Squarespace CDN). Generated by tools/import-projects.cjs.', images: media }, null, 1));

  // Every artpark.in-hosted document (/s/...) linked from any captured page.
  const docs = new Map();
  for (const f of fs.readdirSync(CAP).filter((x) => x.endsWith('.json') && x !== 'index.json')) {
    const d = JSON.parse(fs.readFileSync(path.join(CAP, f), 'utf8'));
    for (const [, h] of d.links || []) if (/artpark\.in\/s\//.test(h)) docs.set(h.split('?')[0], decodeURIComponent(h.split('/s/')[1].split('?')[0]));
  }
  const map = {};
  for (const [url, name] of docs) {
    const ok = await get(url, path.join(DOCS, name));
    map['/s/' + url.split('/s/')[1]] = ok ? '/docs/' + name : null;
    console.log('\n' + (ok ? 'doc ' : 'FAILED ') + name);
  }
  fs.writeFileSync(path.join(ROOT, 'src', 'data', 'docs-map.json'), JSON.stringify(map, null, 1));
})();
